def domain_guide(domain: str, cname_target: str | None) -> dict:
    is_ir = domain.endswith(".ir")
    root = domain.count(".") == 1 or (is_ir and domain.count(".") == 1)
    steps = []
    if is_ir and root:
        steps = [
            "وارد پنل nic.ir شوید و دامنه را از «دامنه‌های من» انتخاب کنید.",
            "گزینه‌ی «ویرایش سرورهای نام (DNS)» را بزنید.",
            "سرورهای نامی را که لیارا برای zone این دامنه اعلام می‌کند وارد کنید (دستیار مقدار دقیق را از API لیارا نمایش می‌دهد).",
            "ذخیره کنید؛ اعمال تغییر در ایرنیک معمولاً ۱ تا ۲۴ ساعت طول می‌کشد.",
            "بعد از آن به دستیار بگویید «دامنه را چک کن» تا اتصال و SSL بررسی شود.",
        ]
    else:
        steps = [
            "در پنل DNS ثبت‌کننده‌ی دامنه (یا Cloudflare) یک رکورد بسازید:",
            f"نوع CNAME، نام {'@ (یا ALIAS/ANAME برای ریشه)' if root else domain.split('.')[0]}، مقدار {cname_target or '<مقدار CNAME لیارا>'}",
            "اگر از Cloudflare استفاده می‌کنید، پروکسی (ابر نارنجی) را تا صدور SSL خاموش نگه دارید.",
            "بعد از چند دقیقه به دستیار بگویید «دامنه را چک کن».",
        ]
    return {"domain": domain, "registrar": "ایرنیک (nic.ir)" if is_ir else "ثبت‌کننده‌ی دامنه", "cname_target": cname_target,
            "steps": steps, "assistant_can_verify": True}
